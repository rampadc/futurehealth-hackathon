"""Safety and productivity measures for the replay day: one crew, three ways of working, judged against
the same MEASURED (synthetic) heat. Writes doc/metrics_replay_<date>.md.

    uv run python tools/replay_metrics.py            # print and write the markdown table
    uv run python tools/replay_metrics.py --bq       # also load the rows into BigQuery metrics.replay_metrics

A. No plan: 5 h straight from 07:00 (midday break respected).  B. The morning plan, followed blindly.
C. Heat-Safe: the plan, the fast loop's alerts, and a re-plan at 09:00 using the minutes actually worked.
"""
from __future__ import annotations

import argparse
from datetime import datetime

import pandas as pd

from heat_safe import rules
from heat_safe.alerts import WORKER_LANGUAGES
from heat_safe.metrics import replay_day_metrics
from heat_safe.paths import ROOT

ROWS = [  # (label, key, unit)
    ("Minutes worked over the ADOSH-SF work limit", "minutes_over_work_limit", "min"),
    ("Work minutes in measured High zone", "work_minutes_high", "min"),
    ("Work minutes in measured Medium zone", "work_minutes_medium", "min"),
    ("Work minutes in measured Low zone", "work_minutes_low", "min"),
    ("Minutes worked in the midday break", "minutes_in_midday_break", "min"),
    ("Minutes worked above a withdrawal limit", "minutes_above_withdrawal_limit", "min"),
    ("Work delivered", "work_delivered_minutes", "min"),
    ("Shortfall", "shortfall_minutes", "min"),
    ("Last work ends at", "finishes_at", ""),
]


def markdown(results: dict, extra: dict, meta: dict) -> str:
    names = list(results)
    lines = [
        f"# Replay metrics: {meta['site']}, {meta['date']}",
        "",
        "> **Prototype replay, not field results.** One day, one crew (steel fixers in shade, "
        f"{meta['hours']:g} h of work, acclimatised). Heat is the real ERA5 replay day with a **SYNTHETIC** site "
        "sensor: a +3 °C heat spike 08:15-09:15 and one faulty reading at 09:40. **No heat illness is "
        "simulated:** the safety measure is work beyond the ADOSH-SF work/rest limits (TG Table 1, rolling 60 "
        "minutes), judged against measured heat, not illness prevented. Generated by `tools/replay_metrics.py` "
        f"(rules {rules.RULES_VERSION}).",
        "",
        "**A. No plan:** 5 h straight from 07:00, the midday break respected (a fair baseline obeys the law). "
        "**B. Morning plan only:** the forecast-based plan, followed whatever the heat. "
        f"**C. Heat-Safe:** the same plan, the fast loop's alerts, and a re-plan at {meta['replan_at']} on measured "
        "heat, counting the minutes actually worked.",
        "",
        "| Measure | " + " | ".join(names) + " |",
        "|---|" + "---:|" * len(names),
    ]
    for label, key, unit in ROWS:
        cells = [f"{results[n][key]}{' ' + unit if unit and results[n][key] != '' else ''}" for n in names]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    by_action = ", ".join(f"{a} {n}" for a, n in extra["alerts_by_action"].items())
    lines += [
        "",
        "## What the fast loop did (C)",
        "",
        f"- Alerts: **{extra['alerts']}** from {extra['readings']} readings ({by_action}); "
        f"{extra['messages_sent']} messages (supervisor + {len(WORKER_LANGUAGES)} worker languages each).",
        f"- Detection delay: **{extra['detection_delay_minutes']} min** from the first reading worse than the plan "
        "to the first alert (readings every 5 minutes).",
        f"- Sensor faults caught: **{extra['sensor_faults_caught']}**; false withdrawals: "
        f"**{extra['false_withdrawals']}**.",
        f"- Minutes the fast loop cut before the re-plan: **{extra['minutes_cut_by_fast_loop']}**; minutes the "
        f"re-plan moved to other hours: **{extra['minutes_moved_by_replan']}** (re-plan from "
        f"{extra['replanned_from']}, {extra['worked_before_replan']} min actually worked before it).",
        "- C's shortfall is work the monitor would not allow under the measured heat (the rolling work limit, "
        "and the 30-minute holds after a withdrawal limit is reached). It is reported to the supervisor as a "
        "shortfall, never squeezed into unsafe time: the cost of protection, made visible.",
        "",
        "## Not measured here",
        "",
        "Adherence, symptom reports and escalations need the worker app and check-ins (roadmap). A full-summer "
        "backtest with synthetic crews is also on the roadmap; this is one replayed day.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--site", default="mussafah")
    ap.add_argument("--date", default="2025-08-01")
    ap.add_argument("--role", default="steel fixer")
    ap.add_argument("--hours", type=float, default=5)
    ap.add_argument("--replan-at", default="09:00")
    ap.add_argument("--bq", action="store_true", help="also load the rows into BigQuery metrics.replay_metrics")
    args = ap.parse_args()

    results, extra, meta = replay_day_metrics(args.site, args.date, args.role, args.hours, args.replan_at)
    md = markdown(results, extra, meta)
    out = ROOT / "doc" / f"metrics_replay_{args.date}.md"
    out.write_text(md, encoding="utf-8")
    print(md)
    print(f"written: {out}")
    if args.bq:
        from google.cloud import bigquery
        rows = [dict(approach=k, **meta, **{c: str(v) for c, v in r.items()}) for k, r in results.items()]
        client = bigquery.Client(location="me-central1")
        table = f"{client.project}.metrics.replay_metrics"
        client.load_table_from_dataframe(pd.DataFrame(rows), table).result()
        print(f"{len(rows)} rows loaded into {table}")


if __name__ == "__main__":
    main()
